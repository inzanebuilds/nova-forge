'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.resolve(__dirname,'..','NOVA_FORGE.html'),'utf8');
const start = html.indexOf('function crc32(');
const end = html.indexOf('async function exportZip(');
assert.ok(start >= 0 && end > start, 'ZIP functions should exist in app source');
const context = { TextEncoder, Uint8Array, DataView };
vm.createContext(context);
vm.runInContext(html.slice(start,end)+';globalThis.archive=zipBytes([["Demo/index.html","<h1>hello</h1>"],["Demo/README.md","# demo"]]);',context);
const bytes = Buffer.from(context.archive);
assert.equal(bytes.readUInt32LE(0),0x04034b50,'local file header signature');
const central = bytes.indexOf(Buffer.from([0x50,0x4b,0x01,0x02]));
assert.ok(central > 0,'central directory header exists');
const endRecord = bytes.lastIndexOf(Buffer.from([0x50,0x4b,0x05,0x06]));
assert.ok(endRecord > central,'end of central directory exists');
assert.equal(bytes.readUInt16LE(endRecord+10),2,'archive should contain two entries');
console.log('PASS: ZIP writer emits a structurally valid two-entry archive');
